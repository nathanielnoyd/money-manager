import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { type Catalog, type CatalogSource, checkCatalog } from "../catalog";
import { type Card, CardFile, type Program, ProgramFile } from "../schema";
import {
  CASH_BACK_PROGRAM,
  cashBackProgram,
  convertCard,
  convertProgram,
  expandVariant,
  isCashBack,
  LEGACY_CARD_SLUGS,
  LEGACY_CARDS_WITHOUT_OCCB_MATCH,
  LEGACY_PROGRAM_SLUGS,
  type OccbCard,
  type OccbCurrency,
  type OccbIssuer,
  type OccbSpendCategory,
  type OccbValuation,
  resolveForNewApplicant,
  taxonomy,
} from "./occb";

/**
 * Regenerate the shipped card catalog from an Open Credit Card Benefits checkout.
 *
 *   pnpm --filter @mm/rewards catalog:import -- --from <occb checkout> [--as-of YYYY-MM-DD]
 *     [--valuations <file>]
 *
 * Each card's terms are resolved for someone applying on the as-of date (default today),
 * converted to this app's format (src/cli/occb.ts), validated, and written to
 * catalog/cards/<issuer>.json and catalog/programs.json, with provenance in
 * catalog/SOURCE.json and the static imports in src/data.ts. It prints a report of
 * everything dropped or approximated; the same sentences are in each card's `notes`.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, "../..");
const catalogDir = path.join(pkg, "catalog");

function args() {
  const a = process.argv.slice(2).filter((x) => x !== "--");
  const get = (name: string) => {
    const i = a.indexOf(name);
    return i >= 0 ? a[i + 1] : undefined;
  };
  const from = get("--from");
  if (!from) {
    console.error(
      "Usage: pnpm --filter @mm/rewards catalog:import -- --from <occb checkout> [--as-of YYYY-MM-DD] [--valuations <file>]",
    );
    process.exit(2);
  }
  const asOf = get("--as-of") ?? new Date().toISOString().slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(asOf)) throw new Error(`--as-of must be YYYY-MM-DD, got ${asOf}`);
  const root = path.resolve(from);
  return {
    root,
    asOf,
    valuations: path.resolve(
      get("--valuations") ?? path.join(root, "examples/value-sets/valuations.yaml"),
    ),
  };
}

const readYaml = <T>(p: string): T => parse(readFileSync(p, "utf8")) as T;
const yamlFiles = (dir: string) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => f.endsWith(".yaml"))
        .sort()
        .map((f) => path.join(dir, f))
    : [];

function loadOccb(root: string) {
  const cat = path.join(root, "catalog");
  const issuers = readYaml<OccbIssuer[]>(path.join(cat, "issuers.yaml"));
  const spend = readYaml<OccbSpendCategory[]>(path.join(cat, "spend-categories.yaml"));
  const currencies = yamlFiles(path.join(cat, "currencies")).map((p) => readYaml<OccbCurrency>(p));
  const cardsDir = path.join(cat, "cards");
  const raw = readdirSync(cardsDir)
    .sort()
    .filter((d) => existsSync(path.join(cardsDir, d, "card.yaml")))
    .map((d): OccbCard => {
      const base = path.join(cardsDir, d);
      const er = path.join(base, "earn-rules.yaml");
      return {
        ...readYaml<OccbCard>(path.join(base, "card.yaml")),
        benefits: yamlFiles(path.join(base, "benefits")).map((p) => readYaml(p)),
        earn_rules: existsSync(er)
          ? (readYaml<{ rules?: OccbCard["earn_rules"] }>(er).rules ?? [])
          : [],
        releases: yamlFiles(path.join(base, "releases")).map((p) => readYaml(p)),
      };
    });
  const cards = raw.map((c) => {
    if (!c.based_on) return c;
    const base = raw.find((b) => b.id === c.based_on?.card);
    if (!base) throw new Error(`${c.id}: based_on names unknown card ${c.based_on.card}`);
    return expandVariant(c, base);
  });
  return { issuers, spend, currencies, cards };
}

function gitCommit(root: string): string | null {
  try {
    return execFileSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  } catch {
    return null;
  }
}

function writeDataTs(files: string[]) {
  const ident = (f: string) =>
    f.replace(/\.json$/, "").replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  const imports = files.map((f) => `import ${ident(f)} from "../catalog/cards/${f}";`).join("\n");
  const entries = files.map((f) => `  "${f}": ${ident(f)},`).join("\n");
  const src = `// GENERATED by src/cli/import-occb.ts from Open Credit Card Benefits; don't edit by hand.
// Static imports so bundlers (Next.js, the worker's esbuild) include the catalog.
${imports}
import programs from "../catalog/programs.json";
import source from "../catalog/SOURCE.json";
import type { Catalog, CatalogSource } from "./catalog";
import { checkCatalog } from "./catalog";
import { CardFile, ProgramFile } from "./schema";

const CARD_FILES: Record<string, unknown> = {
${entries}
};

export const CARD_FILE_NAMES = Object.keys(CARD_FILES);

/** Which generated catalog file each shipped card lives in. */
export const CARD_FILE_OF: ReadonlyMap<string, string> = new Map(
  Object.entries(CARD_FILES).flatMap(([file, f]) =>
    CardFile.parse(f).cards.map((c) => [c.slug, \`cards/\${file}\`] as const),
  ),
);

/** Where the shipped catalog came from (dataset, commit, as-of date, counts). */
export const CATALOG_SOURCE: CatalogSource = source;

function build(): Catalog {
  const catalog: Catalog = {
    programs: ProgramFile.parse(programs).programs,
    cards: Object.values(CARD_FILES).flatMap((f) => CardFile.parse(f).cards),
  };
  const problems = checkCatalog(catalog);
  if (problems.length) throw new Error(\`Invalid card catalog: \${problems.join("; ")}\`);
  return catalog;
}

/** The shipped catalog, validated once at startup. */
export const CATALOG: Catalog = build();
`;
  writeFileSync(path.join(pkg, "src/data.ts"), src);
}

function main() {
  const { root, asOf, valuations: valuationsFile } = args();
  const occb = loadOccb(root);
  const valuations = readYaml<OccbValuation[]>(valuationsFile);
  const tax = taxonomy(occb.spend);
  const currency = (id: string) => occb.currencies.find((c) => c.id === id);
  const issuerName = (id: string) => occb.issuers.find((i) => i.id === id)?.name ?? id;

  const report: string[] = [];
  const problems: string[] = [];

  // Cards. A closed card whose earn rules have all been retired no longer exists (the Wells
  // Fargo Bilt Mastercard), so it isn't shipped.
  const discontinued = occb.cards.filter(
    (c) => c.open_to_applicants === false && !resolveForNewApplicant(c, asOf).earn.length,
  );
  const live = occb.cards.filter((c) => !discontinued.includes(c));
  const converted = live.map((c) => ({
    occb: c,
    ...convertCard(c, asOf, { tax, issuerName, currency }),
  }));
  const byFile = new Map<string, Card[]>();
  for (const c of converted) {
    const parsed = CardFile.shape.cards.element.safeParse(c.card);
    if (!parsed.success) {
      problems.push(
        ...parsed.error.issues.map((i) => `${c.occb.id} ${i.path.join(".")}: ${i.message}`),
      );
      continue;
    }
    byFile.set(c.file, [...(byFile.get(c.file) ?? []), parsed.data]);
  }

  // Programs: one per currency a card earns; 1¢ cashback currencies share `cash_back`.
  const earned = [...new Set(live.map((c) => c.earns).filter((x): x is string => !!x))];
  const programs: Program[] = [];
  const cashMembers: OccbCurrency[] = [];
  for (const id of earned) {
    const cur = currency(id);
    if (!cur) {
      problems.push(`unknown currency ${id}`);
      continue;
    }
    if (isCashBack(cur)) {
      cashMembers.push(cur);
      continue;
    }
    const p = convertProgram(cur, valuations, asOf);
    report.push(...p.notes.map((n) => `program ${n}`));
    programs.push(p.program);
  }
  programs.push(cashBackProgram(cashMembers, valuations, asOf));
  programs.sort((a, b) => a.slug.localeCompare(b.slug));
  const programParse = ProgramFile.safeParse({ programs });
  if (!programParse.success)
    problems.push(
      ...programParse.error.issues.map((i) => `programs ${i.path.join(".")}: ${i.message}`),
    );

  const cards = [...byFile.values()].flat();
  problems.push(...checkCatalog({ programs, cards } satisfies Catalog));
  if (problems.length) {
    console.error(`Import failed with ${problems.length} problem(s):\n- ${problems.join("\n- ")}`);
    process.exit(1);
  }

  // Write
  const cardsDir = path.join(catalogDir, "cards");
  for (const f of readdirSync(cardsDir)) if (f.endsWith(".json")) rmSync(path.join(cardsDir, f));
  const files = [...byFile.keys()].sort();
  const written: string[] = [];
  for (const f of files) {
    const list = (byFile.get(f) ?? []).sort((a, b) => a.slug.localeCompare(b.slug));
    const p = path.join(cardsDir, f);
    writeFileSync(p, `${JSON.stringify({ cards: list }, null, 2)}\n`);
    written.push(p);
  }
  const programsPath = path.join(catalogDir, "programs.json");
  writeFileSync(programsPath, `${JSON.stringify({ programs }, null, 2)}\n`);
  const missingLegacy = Object.entries(LEGACY_CARD_SLUGS)
    .filter(([id]) => !occb.cards.some((c) => c.id === id))
    .map(([, slug]) => slug);
  const source: CatalogSource = {
    dataset: "Open Credit Card Benefits",
    url: "https://github.com/nathanielnoyd/open-credit-card-benefits",
    license: "CC BY 4.0",
    attribution: "Open Credit Card Benefits contributors",
    commit: gitCommit(root),
    asOf,
    valuations: path.relative(root, valuationsFile),
    counts: { cards: cards.length, programs: programs.length, issuers: files.length },
  };
  const sourcePath = path.join(catalogDir, "SOURCE.json");
  writeFileSync(sourcePath, `${JSON.stringify(source, null, 2)}\n`);
  writeDataTs(files);
  written.push(programsPath, sourcePath, path.join(pkg, "src/data.ts"));
  try {
    const biome = createRequire(import.meta.url).resolve("@biomejs/biome/bin/biome");
    execFileSync(process.execPath, [biome, "format", "--write", ...written], { stdio: "ignore" });
  } catch {
    console.warn("Could not run Biome; run `pnpm format` before committing.");
  }

  // Report
  const out: string[] = [];
  out.push(`OCCB ${source.commit ?? "(not a git checkout)"}, terms for new applicants on ${asOf}`);
  out.push(`${cards.length} cards in ${files.length} files, ${programs.length} programs`);
  for (const f of files) out.push(`  ${f}: ${byFile.get(f)?.length ?? 0}`);
  out.push("", "Legacy slugs kept:");
  for (const [id, slug] of Object.entries(LEGACY_CARD_SLUGS)) out.push(`  ${slug} ← ${id}`);
  for (const [id, slug] of Object.entries(LEGACY_PROGRAM_SLUGS)) out.push(`  ${slug} ← ${id}`);
  out.push(`  ${CASH_BACK_PROGRAM} ← ${cashMembers.map((c) => c.id).join(", ")}`);
  out.push("", "Previously shipped cards with no OCCB match (no longer in the catalog):");
  for (const [slug, why] of Object.entries(LEGACY_CARDS_WITHOUT_OCCB_MATCH))
    out.push(`  ${slug}: ${why}`);
  for (const slug of missingLegacy) out.push(`  ${slug}: missing from this OCCB checkout`);
  if (discontinued.length)
    out.push(
      "",
      "Discontinued in OCCB (closed, every earn rule retired), not shipped:",
      ...discontinued.map((c) => `  ${c.id} (${c.name})`),
    );
  out.push("", "Dropped or approximated, by card (also in each card's notes):");
  for (const c of converted) {
    if (!c.notes.length) continue;
    out.push(`  ${c.card.slug} (${c.occb.id}):`);
    for (const n of c.notes) out.push(`    - ${n}`);
  }
  out.push("", "Foreign transaction fee taken from:");
  for (const how of ["waiver", "fee", "notes", "default"] as const) {
    const slugs = converted.filter((c) => c.fxHow === how).map((c) => c.card.slug);
    if (slugs.length) out.push(`  ${how} (${slugs.length}): ${slugs.join(", ")}`);
  }
  if (report.length) out.push("", "Programs:", ...report.map((r) => `  - ${r}`));
  console.log(out.join("\n"));
}

main();
